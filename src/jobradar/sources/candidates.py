def all_candidates() -> list[tuple[str, str]]:
    """Return ``(slug, segment)`` pairs, de-duplicated, first segment winning."""
    seen: set[str] = set()
    out: list[tuple[str, str]] = []
    for batch in (CANDIDATES, CANDIDATES_BATCH2):
        for segment, slugs in batch.items():
            for slug in slugs:
                key = slug.lower()
                if key in seen:
                    continue
                seen.add(key)
                out.append((key, segment))
    return out
